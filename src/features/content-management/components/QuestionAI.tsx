import { useState } from "react";
import {
  Box,
  Typography,
  TextField,
  MenuItem,
  Button,
  Select,
  FormControl,
  CircularProgress,
  FormControlLabel,
  Checkbox,
  Tabs,
  Tab,
} from "@mui/material";
import { Controller, useForm, SubmitHandler } from "react-hook-form";

type ContentType =
  | "multiple_choice"
  | "single_choice"
  | "fill_up"
  | "subjective"
  | "blog"
  | "video";

interface ICreateCourseContent {
  text: string;
  score: number;
  description?: string;
  correctAnswer?: string;
  options?: Array<{
    text: string;
    isCorrect: boolean;
  }>;
  blogTags?: string[];
  videoUrl?: string;
  videoFileName?: string;
  sourceText?: string;
  focusKeyword?: string;
  questionCount?: number;
  difficultyLevel?: string;
  optionsCount?: number;
  blogLength?: string;
  writingTone?: string;
  videoSourceType?: "upload" | "url";
  autoGenerateTitle?: boolean;
  autoGenerateDescription?: boolean;
  generateTranscript?: boolean;
}

interface IQuestionConfiguratorProps {
  type: ContentType;
  unitId: number;
  onClose: () => void;
  onSubmit: (data: ICreateCourseContent) => Promise<void>;
  isLoading: boolean;
}

// Design system constants
const SPACING = {
  section: 4,
  field: 3,
  label: 1,
};

const TYPOGRAPHY = {
  sectionTitle: {
    variant: "h6" as const,
    sx: { fontWeight: 600, mb: SPACING.section },
  },
  fieldLabel: {
    variant: "body2" as const,
    sx: { fontWeight: 500, mb: SPACING.label, color: "text.primary" },
  },
};

const initialSourceText = `GitHub has transformed software development into a globally collaborative process. As the world's leading platform for code hosting and version control, it enables millions of developers to work on projects concurrently, manage changes efficiently, and build open-source communities.

Following its acquisition by Microsoft, GitHub has expanded its services significantly, moving beyond simple Git hosting to offer advanced DevOps tools like GitHub Actions for continuous integration/continuous delivery (CI/CD) and GitHub Copilot for AI-assisted coding. This focus solidifies its role as the central hub for the entire software development lifecycle, from planning and coding to deployment and security.`;

const getQuestionTypeOptions = (contentType: ContentType) => {
  switch (contentType) {
    case "multiple_choice":
      return [{ value: "MCQ", label: "Multiple Choice (MCQ)" }];
    case "single_choice":
      return [{ value: "Single", label: "Single Choice" }];
    case "fill_up":
      return [{ value: "Fill", label: "Fill in the Blanks" }];
    case "subjective":
      return [{ value: "Subjective", label: "Subjective Question" }];
    case "blog":
      return [{ value: "Blog", label: "Blog Content" }];
    case "video":
      return [{ value: "Video", label: "Video Content" }];
    default:
      return [{ value: "MCQ", label: "Multiple Choice (MCQ)" }];
  }
};

const QuestionConfigurator = ({
  type,
  unitId,
  onClose,
  onSubmit: handleFormSubmit,
  isLoading,
}: IQuestionConfiguratorProps) => {
  const [videoSourceType, setVideoSourceType] = useState<"upload" | "url">(
    "upload"
  );

  const effectiveType: ContentType = ((): ContentType => {
    if ((type as string) === "code" || (type as string) === "mcq")
      return "multiple_choice";
    return type;
  })();

  const {
    control,
    handleSubmit,
    formState: { errors },
  } = useForm<ICreateCourseContent>({
    defaultValues: {
      sourceText: initialSourceText,
      focusKeyword: "",
      questionCount: 3,
      difficultyLevel: "Medium",
      optionsCount: 4,
      blogLength: "medium",
      writingTone: "professional",
      videoSourceType: "upload",
      videoUrl: "",
      videoFileName: "",
      autoGenerateTitle: true,
      autoGenerateDescription: true,
      generateTranscript: false,
    },
    mode: "onChange",
  });

  const onSubmit: SubmitHandler<ICreateCourseContent> = async (data) => {
    console.log("🚀 AI Configuration Submitted:", {
      contentType: effectiveType,
      unitId,
      aiConfig: data,
    });

    try {
      await handleFormSubmit(data);
    } catch (error) {
      console.error("❌ AI form submission error:", error);
    }
  };

  const questionTypeOptions = getQuestionTypeOptions(effectiveType);
  const isVideoType = effectiveType === "video";
  const isBlogType = effectiveType === "blog";
  const showQuestionCount = !["blog", "video", "subjective"].includes(
    effectiveType
  );
  const showDifficultyLevel = !["blog", "video"].includes(effectiveType);
  const showOptionsCount =
    effectiveType === "multiple_choice" || effectiveType === "single_choice";

  return (
    <form noValidate onSubmit={handleSubmit(onSubmit)}>
      {/* Section Title */}
      <Typography {...TYPOGRAPHY.sectionTitle}>AI Configuration</Typography>

      {/* ========== VIDEO TYPE ========== */}
      {isVideoType && (
        <>
          <Typography {...TYPOGRAPHY.fieldLabel}>Video Source:</Typography>
          <Tabs
            value={videoSourceType}
            onChange={(_, newValue) => setVideoSourceType(newValue)}
            sx={{ mb: SPACING.label }}
          >
            <Tab label="Upload Video" value="upload" />
            <Tab label="Video URL" value="url" />
          </Tabs>

          {videoSourceType === "upload" && (
            <Box
              sx={{
                border: "2px dashed",
                borderColor: "divider",
                borderRadius: 2,
                p: 4,
                textAlign: "center",
                mb: SPACING.field,
                cursor: "pointer",
                bgcolor: "grey.50",
                transition: "all 0.2s",
                "&:hover": {
                  borderColor: "primary.main",
                  bgcolor: "primary.50",
                },
              }}
            >
              <Typography
                variant="body1"
                color="text.secondary"
                sx={{ mb: 0.5 }}
              >
                Click to upload or drag and drop
              </Typography>
              <Typography variant="caption" color="text.secondary">
                MP4, MOV, AVI (MAX. 500MB)
              </Typography>
            </Box>
          )}

          {videoSourceType === "url" && (
            <Controller
              name="videoUrl"
              control={control}
              rules={{ required: "Video URL is required" }}
              render={({ field }) => (
                <TextField
                  {...field}
                  fullWidth
                  label="Video URL"
                  placeholder="https://example.com/video.mp4"
                  error={!!errors.videoUrl}
                  helperText={errors.videoUrl?.message}
                  sx={{ mb: SPACING.field }}
                />
              )}
            />
          )}

          <Box sx={{ mb: SPACING.field }}>
            <Controller
              name="autoGenerateTitle"
              control={control}
              render={({ field }) => (
                <FormControlLabel
                  control={<Checkbox {...field} checked={field.value} />}
                  label="Auto-generate title from video"
                  sx={{ display: "block", mb: 1 }}
                />
              )}
            />
            <Controller
              name="autoGenerateDescription"
              control={control}
              render={({ field }) => (
                <FormControlLabel
                  control={<Checkbox {...field} checked={field.value} />}
                  label="Auto-generate description from video"
                  sx={{ display: "block", mb: 1 }}
                />
              )}
            />
            <Controller
              name="generateTranscript"
              control={control}
              render={({ field }) => (
                <FormControlLabel
                  control={<Checkbox {...field} checked={field.value} />}
                  label="Generate video transcript"
                  sx={{ display: "block" }}
                />
              )}
            />
          </Box>
        </>
      )}

      {/* ========== NON-VIDEO TYPES: SOURCE MATERIAL ========== */}
      {!isVideoType && (
        <>
          <Typography {...TYPOGRAPHY.fieldLabel}>Source Material:</Typography>
          <Controller
            name="sourceText"
            control={control}
            rules={{ required: "Source material is required" }}
            render={({ field }) => (
              <TextField
                {...field}
                fullWidth
                multiline
                minRows={6}
                maxRows={12}
                placeholder="Paste your source material here..."
                error={!!errors.sourceText}
                helperText={errors.sourceText?.message}
                sx={{ mb: SPACING.field }}
              />
            )}
          />
        </>
      )}

      {/* ========== FOCUS KEYWORD ========== */}
      <Typography {...TYPOGRAPHY.fieldLabel}>
        Focus Keyword / Topic {isBlogType && "(Important for SEO)"}:
      </Typography>
      <Controller
        name="focusKeyword"
        control={control}
        render={({ field }) => (
          <TextField
            {...field}
            fullWidth
            placeholder="e.g., GitHub Actions CI/CD or Repository Forks"
            sx={{ mb: SPACING.field }}
          />
        )}
      />

      {/* ========== CONTENT TYPE ========== */}
      <Typography {...TYPOGRAPHY.fieldLabel}>Content Type:</Typography>
      <FormControl fullWidth sx={{ mb: SPACING.field }}>
        <Select value={questionTypeOptions[0].value} disabled>
          {questionTypeOptions.map((option) => (
            <MenuItem key={option.value} value={option.value}>
              {option.label}
            </MenuItem>
          ))}
        </Select>
      </FormControl>

      {/* ========== BLOG SPECIFIC FIELDS ========== */}
      {isBlogType && (
        <Box sx={{ display: "flex", gap: 2, mb: SPACING.field }}>
          <Box sx={{ flex: 1 }}>
            <Typography {...TYPOGRAPHY.fieldLabel}>Blog Length:</Typography>
            <Controller
              name="blogLength"
              control={control}
              render={({ field }) => (
                <FormControl fullWidth>
                  <Select {...field}>
                    <MenuItem value="short">Short (300-500 words)</MenuItem>
                    <MenuItem value="medium">Medium (500-1000 words)</MenuItem>
                    <MenuItem value="long">Long (1000-2000 words)</MenuItem>
                  </Select>
                </FormControl>
              )}
            />
          </Box>

          <Box sx={{ flex: 1 }}>
            <Typography {...TYPOGRAPHY.fieldLabel}>Writing Tone:</Typography>
            <Controller
              name="writingTone"
              control={control}
              render={({ field }) => (
                <FormControl fullWidth>
                  <Select {...field}>
                    <MenuItem value="professional">Professional</MenuItem>
                    <MenuItem value="casual">Casual</MenuItem>
                    <MenuItem value="technical">Technical</MenuItem>
                    <MenuItem value="conversational">Conversational</MenuItem>
                  </Select>
                </FormControl>
              )}
            />
          </Box>
        </Box>
      )}

      {/* ========== QUESTION TYPES FIELDS ========== */}
      {!isBlogType && !isVideoType && (
        <Box sx={{ display: "flex", gap: 2, mb: SPACING.field }}>
          {showQuestionCount && (
            <Box sx={{ flex: 1 }}>
              <Typography {...TYPOGRAPHY.fieldLabel}>
                Question Count:
              </Typography>
              <Controller
                name="questionCount"
                control={control}
                render={({ field }) => (
                  <FormControl fullWidth>
                    <Select {...field}>
                      {[1, 2, 3, 4, 5].map((count) => (
                        <MenuItem key={count} value={count}>
                          {count}
                        </MenuItem>
                      ))}
                    </Select>
                  </FormControl>
                )}
              />
            </Box>
          )}

          {showDifficultyLevel && (
            <Box sx={{ flex: 1 }}>
              <Typography {...TYPOGRAPHY.fieldLabel}>
                Difficulty Level:
              </Typography>
              <Controller
                name="difficultyLevel"
                control={control}
                render={({ field }) => (
                  <FormControl fullWidth>
                    <Select {...field}>
                      <MenuItem value="Easy">Easy</MenuItem>
                      <MenuItem value="Medium">Medium</MenuItem>
                      <MenuItem value="Hard">Hard</MenuItem>
                    </Select>
                  </FormControl>
                )}
              />
            </Box>
          )}
        </Box>
      )}

      {/* ========== OPTIONS COUNT ========== */}
      {showOptionsCount && (
        <>
          <Typography {...TYPOGRAPHY.fieldLabel}>Options Count:</Typography>
          <Controller
            name="optionsCount"
            control={control}
            render={({ field }) => (
              <FormControl fullWidth sx={{ mb: SPACING.field }}>
                <Select {...field}>
                  {[2, 3, 4, 5].map((count) => (
                    <MenuItem key={count} value={count}>
                      {count}
                    </MenuItem>
                  ))}
                </Select>
              </FormControl>
            )}
          />
        </>
      )}

      {/* ========== ACTION BUTTONS ========== */}
      <Box sx={{ mt: 4, display: "flex", gap: 2, justifyContent: "flex-end" }}>
        <Button
          onClick={onClose}
          variant="outlined"
          disabled={isLoading}
          sx={{ minWidth: 100 }}
        >
          Cancel
        </Button>
        <Button
          type="submit"
          variant="contained"
          disabled={isLoading}
          sx={{ minWidth: 160 }}
        >
          {isLoading ? (
            <>
              <CircularProgress size={20} sx={{ mr: 1 }} color="inherit" />
              Generating...
            </>
          ) : (
            "Generate with AI"
          )}
        </Button>
      </Box>
    </form>
  );
};

export default QuestionConfigurator;
